#!/usr/bin/env node
/** Exact, unconditional calls to the RC2 count helpers. Complex checks remain explicitly pending.
 * Run audit-rc2 first. This pass does not flatten branches or guess casings from hint dots.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { countChecks } from './count-checks.mjs';
const audit = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const entries = {};
for (const entry of audit.entries) {
  const checks = countChecks(entry.chain);
  entries[entry.id] = {
    controller: entry.controller,
    source: entry.source,
    inheritance: entry.chain.map(({ class: name, path, sha256 }) => ({ class: name, path, sha256 })),
    status: 'partial',
    counts: checks,
  };
}
writeFileSync(
  'src/data/constraints.rc2.generated.json',
  JSON.stringify(
    {
      $comment: 'Generated by tools/gt-source/constraints-rc2.mjs. Counts are one part of the full audit.',
      rulesVersion: audit.lock.pack,
      entries,
    },
    null,
    2,
  ) + '\n',
);
// Evidence URLs and hashes stay in the audit registry; the browser needs only executable counts.
writeFileSync(
  'src/data/constraints.runtime.generated.json',
  JSON.stringify(
    Object.fromEntries(
      Object.entries(entries)
        .filter(([, entry]) => entry.counts.length)
        .map(([id, entry]) => [id, entry.counts.map(({ source, ...count }) => count)]),
    ),
    null,
    2,
  ) + '\n',
);
console.log(
  JSON.stringify({
    controllers: Object.keys(entries).length,
    withCounts: Object.values(entries).filter((e) => e.counts.length).length,
  }),
);
